import jsPDF from 'jspdf';

export function exportToCSV(filename, rows) {
  if (!rows || !rows.length) return;
  const keys = Object.keys(rows[0]);
  const csvContent =
    'data:text/csv;charset=utf-8,' +
    [keys.join(','), ...rows.map((row) => keys.map((k) => `"${row[k] ?? ''}"`).join(','))].join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

export function exportPredictionPDF(prediction) {
  const doc = new jsPDF();
  const title = 'SkyIntel AI — Weather Intelligence Certificate';
  const subtitle = 'Developed by DSMV Labs';

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(2, 132, 199);
  doc.text(title, 14, 20);

  doc.setFont('helvetica', 'italic');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text(subtitle, 14, 27);

  doc.setLineWidth(0.5);
  doc.setDrawColor(2, 132, 199);
  doc.line(14, 32, 196, 32);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);

  let y = 42;
  doc.text(`Target City: ${prediction.city || 'N/A'}`, 14, y); y += 8;
  doc.text(`Report Date: ${prediction.created_at ? new Date(prediction.created_at).toLocaleString() : 'N/A'}`, 14, y); y += 8;
  doc.text(`Rain Probability: ${prediction.rain_probability}%`, 14, y); y += 8;
  doc.text(`Flood Risk Level: ${prediction.flood_risk}`, 14, y); y += 8;
  doc.text(`Clothes Drying Feasibility: ${prediction.drying_condition}`, 14, y); y += 8;
  doc.text(`ML Model Evaluated: ${(prediction.selected_model || 'Random Forest').toUpperCase()}`, 14, y); y += 12;

  doc.setFont('helvetica', 'bold');
  doc.text('Smart AI Actionable Advisory:', 14, y); y += 8;
  doc.setFont('helvetica', 'normal');

  const recs = Array.isArray(prediction.recommendations) ? prediction.recommendations : [prediction.recommendations];
  recs.forEach((rec) => {
    const lines = doc.splitTextToSize(`• ${rec}`, 180);
    doc.text(lines, 14, y);
    y += lines.length * 6 + 2;
  });

  y += 10;
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text('Generated by SkyIntel AI Platform. © 2026 DSMV Labs', 14, 280);

  doc.save(`SkyIntel_Report_${prediction.city || 'Location'}.pdf`);
}
